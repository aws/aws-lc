static int do_d2i_x509(void) {
  const uint8_t *ptr = kCertDER;
  X509 *cert = d2i_X509(NULL, &ptr, sizeof(kCertDER));
  if (cert == NULL) {
    return 0;
  }
  // X509_get_pubkey decodes the SubjectPublicKeyInfo and reaches the EVP table.
  EVP_PKEY *pkey = X509_get_pubkey(cert);
  int ok = ptr == kCertDER + sizeof(kCertDER) && pkey != NULL;
  EVP_PKEY_free(pkey);
  X509_free(cert);
  return ok;
}
