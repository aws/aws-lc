int main(void) {
  if (!do_sha256() || !do_aes_256_gcm() || !do_ecdsa_p256() || !do_x25519() ||
      !do_ed25519()) {
    fprintf(stderr, "crypto self-check failed\n");
    return 1;
  }
#if defined(AWSLC_SIZE_CHECK_EVP_PARSE)
  if (!do_evp_parse()) {
    fprintf(stderr, "EVP parse self-check failed\n");
    return 1;
  }
#endif
#if defined(AWSLC_SIZE_CHECK_D2I_X509)
  if (!do_d2i_x509()) {
    fprintf(stderr, "X.509 parse self-check failed\n");
    return 1;
  }
#endif
  printf("ok\n");
  return 0;
}
