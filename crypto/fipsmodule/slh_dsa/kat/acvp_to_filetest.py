"""Converts NIST ACVP-Server SLH-DSA (FIPS 205) vectors to FileTest format.

Usage:
  acvp_to_filetest.py <dir with SLH-DSA-{keyGen,sigGen,sigVer}-FIPS205
                       .internalProjection.json> <output dir> <acvp version>

The JSON files come from
https://github.com/usnistgov/ACVP-Server/tree/<version>/gen-val/json-files/
(SLH-DSA-<mode>-FIPS205/internalProjection.json).

Only the parameter sets in PARAMETER_SETS are emitted. Signature vectors
cover the internal interface (FIPS 205 Algorithms 19 and 20), pure SLH-DSA
(Algorithms 22 and 24) and HashSLH-DSA with SHAKE128 and SHAKE256 (Algorithms
23 and 25), the pre-hash functions AWS-LC supports.

To keep the files small, sigGen keeps the SIGGEN_PER_KIND vectors with the
shortest messages for each kind of signature (interface, deterministic or
hedged, and pre-hash function), and sigVer keeps one vector for each kind and
each reason a signature should verify or not.
"""

import hashlib
import json
import os
import sys

PREHASH_FUNCTIONS = ["SHAKE-128", "SHAKE-256"]

SIGGEN_PER_KIND = 2

PARAMETER_SETS = ["SLH-DSA-SHAKE-128s", "SLH-DSA-SHAKE-192s",
                  "SLH-DSA-SHAKE-256s"]


def file_name(param_set, mode):
    # SLH-DSA-SHAKE-128s -> SLHDSA_SHAKE_128S
    name = param_set.replace("SLH-DSA", "SLHDSA").replace("-", "_").upper()
    return f"{name}_ACVP_{mode}.txt"


def load(src_dir, mode):
    path = os.path.join(src_dir,
                        f"SLH-DSA-{mode}-FIPS205.internalProjection.json")
    with open(path, "rb") as f:
        raw = f.read()
    return json.loads(raw), hashlib.sha256(raw).hexdigest()


def header(version, mode, digest, param_set):
    return (f"# NIST ACVP-Server {version}, {param_set}, {mode}.\n"
            f"# Source: gen-val/json-files/SLH-DSA-{mode}-FIPS205/"
            f"internalProjection.json\n"
            f"# SHA-256 of source: {digest}\n"
            f"# Generated by acvp_to_filetest.py. Do not edit.\n\n")


def emit(out_dir, param_set, mode, hdr, blocks):
    path = os.path.join(out_dir, file_name(param_set, mode))
    with open(path, "w") as f:
        f.write(hdr)
        f.write("\n\n".join(blocks))
        f.write("\n")
    print(f"{path}: {len(blocks)} vectors")


def interface(group, test):
    """Returns "internal", "pure" or "prehash", or None to skip the test."""
    if group["signatureInterface"] == "internal":
        return "internal"
    if group["preHash"] == "pure":
        return "pure"
    if test["hashAlg"] in PREHASH_FUNCTIONS:
        return "prehash"
    return None


def key_gen(groups, param_set):
    blocks = []
    for g in groups:
        if g["parameterSet"] != param_set:
            continue
        for t in g["tests"]:
            blocks.append("\n".join(l.rstrip() for l in [
                f"tcId = {t['tcId']}",
                f"sk_seed = {t['skSeed']}",
                f"sk_prf = {t['skPrf']}",
                f"pk_seed = {t['pkSeed']}",
                f"pk = {t['pk']}",
                f"sk = {t['sk']}",
            ]))
    return blocks


def select(candidates, per_key):
    """Keeps the |per_key| (key, test, block) entries with the shortest
    messages for each key, in tcId order."""
    by_key = {}
    for key, t, block in candidates:
        by_key.setdefault(key, []).append((len(t["message"]), t["tcId"], block))
    kept = []
    for entries in by_key.values():
        kept += sorted(entries)[:per_key]
    return [block for _, _, block in sorted(kept, key=lambda e: e[1])]


def sig_gen(groups, param_set):
    candidates = []
    for g in groups:
        if g["parameterSet"] != param_set:
            continue
        for t in g["tests"]:
            iface = interface(g, t)
            if iface is None:
                continue
            # Deterministic signing has no additional randomness; an empty
            # addrnd selects it.
            addrnd = "" if g["deterministic"] else t["additionalRandomness"]
            lines = [f"tcId = {t['tcId']}", f"interface = {iface}",
                     f"sk = {t['sk']}", f"msg = {t['message']}"]
            if iface != "internal":
                lines.append(f"ctx = {t['context']}")
            if iface == "prehash":
                lines.append(f"hash = {t['hashAlg']}")
            lines += [f"addrnd = {addrnd}", f"sig = {t['signature']}"]
            key = (iface, g["deterministic"], t.get("hashAlg"))
            candidates.append(
                (key, t, "\n".join(l.rstrip() for l in lines)))
    return select(candidates, SIGGEN_PER_KIND)


def sig_ver(groups, param_set):
    candidates = []
    for g in groups:
        if g["parameterSet"] != param_set:
            continue
        for t in g["tests"]:
            iface = interface(g, t)
            if iface is None:
                continue
            lines = [f"# {t['reason']}"] if t.get("reason") else []
            lines += [f"tcId = {t['tcId']}", f"interface = {iface}",
                      f"pk = {t['pk']}", f"msg = {t['message']}"]
            if iface != "internal":
                lines.append(f"ctx = {t['context']}")
            if iface == "prehash":
                lines.append(f"hash = {t['hashAlg']}")
            lines += [f"sig = {t['signature']}",
                      f"result = {'pass' if t['testPassed'] else 'fail'}"]
            key = (iface, t.get("hashAlg"), t.get("reason"), t["testPassed"])
            candidates.append(
                (key, t, "\n".join(l.rstrip() for l in lines)))
    return select(candidates, 1)


def main():
    if len(sys.argv) != 4:
        sys.exit(__doc__)
    src_dir, out_dir, version = sys.argv[1:4]
    for mode, convert in [("keyGen", key_gen), ("sigGen", sig_gen),
                          ("sigVer", sig_ver)]:
        data, digest = load(src_dir, mode)
        assert data["algorithm"] == "SLH-DSA" and data["mode"] == mode
        for param_set in PARAMETER_SETS:
            blocks = convert(data["testGroups"], param_set)
            assert blocks, f"no {mode} vectors for {param_set}"
            emit(out_dir, param_set, mode,
                 header(version, mode, digest, param_set), blocks)


if __name__ == "__main__":
    main()
